// Browser interaction on HTML rendered by real MockMvc/Thymeleaf/H2 tests.
// POSTs below are intercepted contracts, not claims of live SQL Server testing.
const { test, expect } = require('@playwright/test')
const fs = require('node:fs'), path = require('node:path')
const root = path.resolve(__dirname, '..')
async function open(page, name) {
  await page.route('**/*', async route => {
    const url = new URL(route.request().url())
    if (url.hostname !== 'f6s-ui.test') return route.abort()
    let file = url.pathname.startsWith('/proof/')
      ? path.join(root, 'target/refresh-ui', path.basename(url.pathname) + '.html')
      : path.join(root, 'src/main/resources/static', url.pathname)
    if (!file.startsWith(root) || !fs.existsSync(file) || !fs.statSync(file).isFile()) return route.fulfill({ status: 404, body: '' })
    const ext = path.extname(file)
    await route.fulfill({ body: fs.readFileSync(file), contentType: ({ '.html':'text/html', '.css':'text/css', '.js':'application/javascript', '.svg':'image/svg+xml' })[ext] || 'application/octet-stream' })
  })
  await page.goto('http://f6s-ui.test/proof/' + name)
}
test('customer can type a quantity after selecting a variant', async ({page}) => {
  await open(page, 'product')
  await page.getByRole('combobox', {name:'Kích cỡ',exact:true}).click()
  await page.locator('#picker-size-1-listbox [role=option]').first().click()
  await page.getByLabel('Số lượng:', {exact:true}).fill('3')
  await expect(page.locator('#quantity')).toHaveValue('3')
  await expect(page.locator('#stock-status')).toContainText('12')
  await expect(page.locator('.stock-summary').first()).toContainText('1')
})
test('checkout fields are editable and submit updated receiver information', async ({page}) => {
  await open(page, 'checkout')
  await page.getByLabel('Họ tên người nhận *', {exact:true}).fill('Người nhận mới')
  await page.getByLabel('Số điện thoại *', {exact:true}).fill('0987654321')
  await page.getByLabel('Thư điện tử *', {exact:true}).fill('receiver@example.test')
  await page.getByLabel('Địa chỉ giao hàng *', {exact:true}).fill('456 Đường kiểm thử Hà Nội')
  await page.locator('#paymentMethod').selectOption('COD')
  const request=page.waitForRequest(r=>r.method()==='POST' && r.url().endsWith('/checkout/place'))
  await page.getByRole('button', {name:'Đặt hàng',exact:true}).click()
  const data=new URLSearchParams((await request).postData())
  expect(data.get('receiverName')).toBe('Người nhận mới')
  expect(data.get('paymentMethod')).toBe('COD')
  expect(data.get('checkoutToken')).toBeTruthy()
})
test('POS clearly displays stock, variants and sequential steps', async ({page}, testInfo) => {
  await open(page, 'pos')
  await expect(page.getByRole('navigation',{name:'Quy trình bán tại quầy'})).toBeVisible()
  await expect(page.locator('.pos-product .stock-summary')).toContainText('Tồn: 12 đôi')
  await page.getByRole('button',{name:'Xem biến thể / Thêm',exact:true}).click()
  await expect(page.locator('#pos-product-dialog')).toBeVisible()
  await expect(page.locator('#pos-product-summary')).toContainText('1 biến thể')
  await expect(page.locator('#pos-variant')).toContainText('còn 12')
  await page.locator('#pos-quantity').fill('2')
  await page.locator('[data-pos-close]').click()
  await page.screenshot({path:testInfo.outputPath('pos.png'),fullPage:true})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy()
})
