import { test, expect } from '@playwright/test'
test('customer profile and default delivery address', async ({ page }, info) => {
  test.skip(!process.env.E2E_ADMIN_PASSWORD, 'Disposable database and explicit admin required')
  const name = 'Khách E2E ' + info.project.name + Date.now()
  const phone = '09' + String(Date.now()).slice(-8)
  await page.goto('/admin/login')
  await page
    .getByLabel('Tài khoản', { exact: true })
    .fill(process.env.E2E_ADMIN_USERNAME || 'admin')
  await page.getByLabel('Mật khẩu', { exact: true }).fill(process.env.E2E_ADMIN_PASSWORD)
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Tổng quan kinh doanh' })).toBeVisible()
  if (info.project.name === 'mobile')
    await page.getByRole('button', { name: 'Ẩn/hiện menu quản trị' }).click()
  await page
    .getByRole('navigation', { name: 'Quản trị' })
    .getByRole('link', { name: 'Khách hàng', exact: true })
    .click()
  await page.getByRole('button', { name: '+ Thêm khách hàng' }).click()
  await page.getByLabel('Họ và tên', { exact: true }).fill(name)
  await page.getByLabel('Số điện thoại', { exact: true }).fill(phone)
  await page.getByRole('button', { name: 'Lưu hồ sơ', exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: name })
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: 'Địa chỉ', exact: true }).click()
  await page.getByLabel('Tên người nhận', { exact: true }).fill(name)
  await page.getByLabel('Điện thoại nhận hàng', { exact: true }).fill(phone)
  await page.getByLabel('Tỉnh / Thành phố', { exact: true }).fill('Hà Nội')
  await page.getByLabel('Quận / Huyện', { exact: true }).fill('Ba Đình')
  await page.getByLabel('Phường / Xã', { exact: true }).fill('Kim Mã')
  await page.getByLabel('Số nhà / Đường', { exact: true }).fill('10 Phố kiểm thử')
  await page.getByRole('button', { name: 'Lưu địa chỉ', exact: true }).click()
  await expect(page.getByText('Mặc định', { exact: true })).toBeVisible()
})
